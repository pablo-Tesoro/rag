"""Result tables of README.md, rendered from the runs saved in evals/results/.

Every number in the README must come from a saved run. The tables live between two markers
in README.md: `python -m evals.readme_tables --write` renders them from the files listed in
SOURCES, and `tests/unit/test_readme.py` fails if the README and the files disagree, so a
number can be neither edited by hand nor left stale.

    uv run python -m evals.readme_tables          # check (exit 1 if the README is stale)
    uv run python -m evals.readme_tables --write  # rewrite the block
"""

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

from evals.runinfo import REPO_ROOT, RESULTS_DIR

README = REPO_ROOT / "README.md"
START = "<!-- results:start: generated by `python -m evals.readme_tables --write` -->"
END = "<!-- results:end -->"

# The runs the README reports. Changing a number means pointing this at another saved run.
SOURCES = {
    "agent_test": "20261001T122733Z_agent_test.json",
    "agent_dev": "20261001T103057Z_agent_dev.json",
    "agent_dev_dense": "20261001T121247Z_agent_dev.json",
    "agent_dev_bm25": "20261001T121759Z_agent_dev.json",
    "retrieval_dev": "20260930T175343Z_retrieval_dev.json",
    "retrieval_test": "20261001T121958Z_retrieval_test.json",
    "judge_controls": "20261001T095702Z_judge_controls.json",
}
MODES = ("dense", "bm25", "hybrid")
Run = dict[str, Any]


def load(results_dir: Path = RESULTS_DIR) -> dict[str, Run]:
    return {
        name: json.loads((results_dir / file).read_text(encoding="utf-8"))
        for name, file in SOURCES.items()
    }


def _rate(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.2f}"


def _passed(run: Run) -> tuple[int, int]:
    return sum(r["passed"] for r in run["runs"]), len(run["runs"])


def _cases_passing_every_repeat(run: Run) -> tuple[int, int]:
    by_case: dict[str, list[bool]] = defaultdict(list)
    for r in run["runs"]:
        by_case[r["case_id"]].append(r["passed"])
    return sum(all(v) for v in by_case.values()), len(by_case)


def _agent_column(run: Run) -> list[str]:
    summary, checks = run["summary"], run["summary"]["checks"]
    passed, total = _passed(run)
    stable, cases = _cases_passing_every_repeat(run)
    gate = "PASS" if run["gate"]["passed"] else "FAIL: " + "; ".join(run["gate"]["reasons"])
    return [
        f"{summary['cases']} cases × {summary['repeats']}",
        gate,
        f"{_rate(summary['pass_rate'])} ({passed}/{total})",
        f"{_rate(summary['pass_hat_k'])} ({stable}/{cases})",
        f"{len(summary['critical_failed'])} of {summary['critical_cases']}",
        str(summary["safety_violations"]),
        _rate(checks["answer_correct"]),
        _rate(checks["grounded"]),
        _rate(checks["abstention"]),
        _rate(checks["approval"]),
        _rate(summary["evidence_recall"]),
        str(summary["errors"]),
    ]


def results_table(test: Run, dev: Run) -> list[str]:
    labels = [
        "Runs",
        "Quality gate",
        "Pass rate (runs)",
        "pass^k (cases passing every repeat)",
        "Critical cases failing any repeat",
        "Safety violations (leaks, forbidden calls, unapproved writes)",
        "Answer correct (judge)",
        "Grounded in the retrieved evidence (judge)",
        "Abstains when there is no evidence",
        "Incident approval flow",
        "Evidence recall (agent retrieval)",
        "Runs with errors",
    ]
    rows = zip(labels, _agent_column(test), _agent_column(dev), strict=True)
    return [
        "| | Test (held out) | Dev |",
        "|---|---|---|",
        *(f"| {label} | {t} | {d} |" for label, t, d in rows),
    ]


def ablation_table(data: dict[str, Run]) -> list[str]:
    retrieval = data["retrieval_dev"]["summary"]
    agent = {"dense": data["agent_dev_dense"], "bm25": data["agent_dev_bm25"]}
    agent["hybrid"] = data["agent_dev"]
    lines = [
        "| Retrieval mode | Recall@5 (no LLM) | MRR@10 (no LLM) | Agent pass rate | "
        "Answer correct | Grounded | Agent evidence recall | Critical failures |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for mode in MODES:
        run, checks = agent[mode], agent[mode]["summary"]["checks"]
        passed, total = _passed(run)
        lines.append(
            f"| {mode} | {_rate(retrieval[mode]['recall'])} | {_rate(retrieval[mode]['mrr'])} | "
            f"{_rate(run['summary']['pass_rate'])} ({passed}/{total}) | "
            f"{_rate(checks['answer_correct'])} | {_rate(checks['grounded'])} | "
            f"{_rate(run['summary']['evidence_recall'])} | "
            f"{len(run['summary']['critical_failed'])} |"
        )
    return lines


def retrieval_table(dev: Run, test: Run) -> list[str]:
    lines = [
        "| Mode | Recall@5 dev | MRR@10 dev | Recall@5 test | MRR@10 test |",
        "|---|---|---|---|---|",
    ]
    for mode in MODES:
        d, t = dev["summary"][mode], test["summary"][mode]
        lines.append(
            f"| {mode} | {_rate(d['recall'])} | {_rate(d['mrr'])} | "
            f"{_rate(t['recall'])} | {_rate(t['mrr'])} |"
        )
    return lines


def usage_table(test: Run, dev: Run) -> list[str]:
    def row(label: str, run: Run) -> str:
        usage, runs = run["usage"], len(run["runs"])
        tokens = usage["agent_tokens"]["input"] + usage["agent_tokens"]["output"]
        cost = (usage["agent_cost_usd"] or 0) + (usage["judge_cost_usd"] or 0)
        return (
            f"| {label} | {usage['llm_calls_agent'] / runs:.1f} | {tokens / runs:,.0f} | "
            f"${cost / runs:.4f} | {usage['latency_s']['p50']:.0f} s / "
            f"{usage['latency_s']['p95']:.0f} s |"
        )

    return [
        "| Split | Agent LLM calls per run | Agent tokens per run | "
        "Paid-tier equivalent per run (agent + judge) | Latency p50 / p95 |",
        "|---|---|---|---|---|",
        row("Test", test),
        row("Dev", dev),
    ]


def _source(name: str, run: Run) -> str:
    config = run["config"]
    details = [f"commit `{config['commit']}`"]
    for key in ("agent_prompt", "retrieval_mode", "judge_model"):
        if key in config:
            details.append(f"`{config[key]}`")
    return f"- `{name}`: `evals/results/{SOURCES[name]}` ({', '.join(details)})"


def render(data: dict[str, Run]) -> str:
    controls = data["judge_controls"]
    agreed = sum(c["agrees"] for c in controls["controls"])
    test_config = data["agent_test"]["config"]
    lines = [
        START,
        "",
        f"Agent `{test_config['agent_model']}` with `{test_config['agent_prompt']}`, "
        f"`{test_config['retrieval_mode']}` retrieval; judge `{test_config['judge_model']}`.",
        "",
        *results_table(data["agent_test"], data["agent_dev"]),
        "",
        "**Retrieval-mode ablation on dev.** Agent runs: dense "
        f"{len(data['agent_dev_dense']['runs'])}, bm25 {len(data['agent_dev_bm25']['runs'])}, "
        f"hybrid {len(data['agent_dev']['runs'])}.",
        "",
        *ablation_table(data),
        "",
        "**Retrieval without the LLM** (the raw question as the query).",
        "",
        *retrieval_table(data["retrieval_dev"], data["retrieval_test"]),
        "",
        f"**Judge controls:** {agreed} of {len(controls['controls'])} known verdicts agreed "
        f"({', '.join(c['control'] for c in controls['controls'])}).",
        "",
        "**Usage.** Latency includes the waits of the free-tier rate limiter; the actual cost on "
        "the free tier is 0.",
        "",
        *usage_table(data["agent_test"], data["agent_dev"]),
        "",
        "Sources:",
        "",
        *(_source(name, run) for name, run in data.items()),
        "",
        END,
    ]
    return "\n".join(lines)


def replace_block(text: str, block: str) -> str:
    start, end = text.find(START), text.find(END)
    if start == -1 or end == -1 or end < start:
        raise ValueError("README.md has no results markers")
    return text[:start] + block + text[end + len(END) :]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--write", action="store_true", help="Rewrite the block in README.md.")
    args = parser.parse_args()
    text = README.read_text(encoding="utf-8")
    updated = replace_block(text, render(load()))
    if args.write:
        README.write_text(updated, encoding="utf-8")
        print("README.md results block updated.")
    elif updated != text:
        print("README.md results block is stale: run with --write.")
        sys.exit(1)
    else:
        print("README.md results block is up to date.")


if __name__ == "__main__":
    main()
